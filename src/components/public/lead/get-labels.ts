import { getTranslations } from "next-intl/server";
import { STUDENT_COUNTRIES } from "@/lib/constants";
import type { LeadLabels } from "./labels";

const ERROR_TOKENS = ["REQUIRED", "TOO_LONG", "INVALID", "UNKNOWN_VALUE", "DUPLICATE", "PHONE_INVALID", "PROGRAMMES_MIN_3", "UNIVERSITY_OR_PROGRAMME_REQUIRED", "CONSENT_REQUIRED"] as const;

/** Reads the `apply` namespace into the plain object the lead forms take as props. */
export async function getLeadLabels(locale: string): Promise<LeadLabels> {
  const t = await getTranslations({ locale, namespace: "apply" });
  const errors = Object.fromEntries(ERROR_TOKENS.map((token) => [token, t(`errors.${token}`)]));
  const countries = Object.fromEntries(STUDENT_COUNTRIES.map((code) => [code, t(`countries.${code}`)]));
  return {
    name: t("fields.name"),
    whatsapp: t("fields.whatsapp"),
    whatsappHelp: t("fields.whatsappHelp"),
    country: t("fields.country"),
    chooseCountry: t("fields.chooseCountry"),
    email: t("fields.email"),
    emailHelp: t("fields.emailHelp"),
    university: t("fields.university"),
    chooseUniversity: t("fields.chooseUniversity"),
    qualification: t("fields.qualification"),
    qualOlevel: t("fields.qualOlevel"),
    qualGrade: t("fields.qualGrade"),
    results: t("fields.results"),
    resultsHelp: t("fields.resultsHelp"),
    subject: t("fields.subject"),
    grade: t("fields.grade"),
    addResult: t("fields.addResult"),
    removeRow: t("fields.removeRow"),
    programmes: t("programmes.title"),
    programmesHelp: t("programmes.help"),
    searchProgrammes: t("programmes.search"),
    noProgrammeMatch: t("programmes.noMatch"),
    chosen: t("programmes.chosen"),
    rank: t("programmes.rank", { rank: "{rank}" }),
    add: t("programmes.add"),
    remove: t("programmes.remove"),
    moveUp: t("programmes.moveUp"),
    moveDown: t("programmes.moveDown"),
    consent: t("consent.text", { link: "{link}" }),
    privacyLink: t("consent.link"),
    continue: t("actions.continue"),
    saving: t("actions.saving"),
    sending: t("actions.sending"),
    cancel: t("actions.cancel"),
    close: t("actions.close"),
    quickTitle: t("quick.title"),
    quickIntro: t("quick.intro"),
    quickAbout: t("quick.about", { university: "{university}" }),
    applyTitle: t("apply.title"),
    applyIntro: t("apply.intro"),
    savedBanner: t("apply.savedBanner"),
    removeFromPhone: t("apply.removeFromPhone"),
    confirmRemove: t("apply.confirmRemove"),
    keep: t("apply.keep"),
    resendNow: t("apply.resendNow"),
    statusSaved: t("status.saved"),
    statusSending: t("status.sending"),
    statusSent: t("status.sent"),
    statusNotSent: t("status.notSent"),
    statusRejected: t("status.rejected"),
    offlineNote: t("status.offlineNote"),
    doneSentTitle: t("done.sentTitle"),
    doneSavedTitle: t("done.savedTitle"),
    doneSentBody: t("done.sentBody"),
    doneSavedBody: t("done.savedBody"),
    reference: t("done.reference"),
    openWhatsApp: t("done.openWhatsApp"),
    whatsappBlocked: t("done.whatsappBlocked"),
    noWhatsApp: t("done.noWhatsApp"),
    completeApplication: t("done.completeApplication"),
    couldntSave: t("done.couldntSave"),
    couldntSaveHelp: t("done.couldntSaveHelp"),
    copyDetails: t("done.copyDetails"),
    copied: t("done.copied"),
    limitedRate: t("done.limitedRate"),
    limitedNumber: t("done.limitedNumber"),
    turnstilePrompt: t("done.turnstilePrompt"),
    turnstileFailed: t("done.turnstileFailed"),
    waQuick: t("whatsapp.quick", { name: "{name}", country: "{country}", ref: "{ref}", about: "{about}" }),
    waFull: t("whatsapp.full", { name: "{name}", country: "{country}", ref: "{ref}", programmes: "{programmes}" }),
    waAboutUniversity: t("whatsapp.aboutUniversity", { university: "{university}" }),
    waAboutProgramme: t("whatsapp.aboutProgramme", { programme: "{programme}", university: "{university}" }),
    waProgrammes: t("whatsapp.programmes", { count: "{count}", first: "{first}" }),
    errors,
    countries,
  };
}
